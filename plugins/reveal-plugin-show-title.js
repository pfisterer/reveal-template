/*
	Create a title slide automatically from the lecture metadata that
	dennis_build embeds into the page (farberg_reveal_template.info,
	sourced from the lecture repo's package.json at build time):

	{
		title: "Title of the presentation",
		homepage: "https://the.url/to/the/slides",
		authors: [
			{ "name": "John Doe", homepage:"https://jon.doe.com" },
			{ "name": "Jane Doe", homepage:"https://jane.doe.com" },
		]
	}

	Example markdown:
		<div class="lecturetitle">This is the Title of the Presentation</div>
*/

function showTitle(deck, packageJson) {
	let lectureTitle = packageJson.title

	let authors = packageJson.authors || []
	let authorBlock = authors.map(entry => `<a href="${entry.homepage}"> ${entry.name}</a>`).join(", ")

	// <div class="coursetitle"></div> alone is enough for the course title slide: it gets the title slide styles of .lecturetitle (its text is ignored)
	for (const el of deck.getSlidesElement().querySelectorAll(".coursetitle:not(.lecturetitle)")) el.classList.add("lecturetitle")

	for (let el of deck.getSlidesElement().getElementsByClassName("lecturetitle")) {
		let slideTitle = el.innerText;
		// Course title slide (<div class="coursetitle"></div>): only the lecture title and the lecturers, no chapter
		const isCourse = el.classList.contains("coursetitle")

		// Mark the enclosing slide so simplemenu hides on it (handled in dhbw.css
		// via body.hide-menubar). Equivalent to writing in the markdown:
		//   <!-- .slide: data-state="hide-menubar" -->
		// Reveal mirrors data-state to body classes on every slidechanged event.
		// We run here during plugin init — before Reveal's first slidechanged
		// fires — so setting data-state now lets Reveal mirror it automatically
		// when the initial slide is shown. The getCurrentSlide() guard below is
		// a belt-and-suspenders fallback for the case where the title slide is
		// already the current one by the time this runs.
		const section = el.closest('section');
		if (section) {
			section.setAttribute('data-state', 'hide-menubar');
			if (section === deck.getCurrentSlide()) {
				document.body.classList.add('hide-menubar');
			}
		}

		// Chapter number of the deck ("04e"), from the page config of dennis_build
		const configEl = document.getElementById('farberg-deck-config')
		const meta = (configEl ? JSON.parse(configEl.textContent).deck : null) || {}
		const number = meta.number ? `${meta.number}${meta.sub || ''}` : ''

		if (isCourse) {
			el.innerHTML = `
				<div class="title_layout title_layout_course">
					<h1 class="title_chapter title_course">${lectureTitle}</h1>
					<div class="title_rule"></div>
					<div class="title_course_authors">${authorBlock}</div>
				</div>
			`;
			continue
		}

		el.innerHTML = `
				<div class="title_layout">
					<div class="title_lecture">${lectureTitle}</div>
					<div class="title_main">
						${number ? `<div class="title_number">${number}</div>` : ''}
						<h1 class="title_chapter">${slideTitle}</h1>
						<div class="title_rule"></div>
					</div>
					<div class="title_footer">
						<div class="title_authors">${authorBlock}</div>
					</div>
				</div>
			`;

		document.title = `${lectureTitle} - ${slideTitle}`
	}

}

// Section slides (a slide with nothing but a h1, e.g. "# Observability") become dividers: class section_divider plus the chapter ("04b · Observability") in the top right corner
function markSectionSlides(deck) {
	const configEl = document.getElementById('farberg-deck-config')
	const meta = (configEl ? JSON.parse(configEl.textContent).deck : null) || {}
	const context = [meta.number ? `${meta.number}${meta.sub || ''}` : '', meta.title || ''].filter(Boolean).join('\u2002·\u2002')
	for (const section of deck.getSlidesElement().querySelectorAll('section')) {
		if (section.querySelector('section') || section.querySelector('.lecturetitle')) continue
		const content = [...section.children].filter(el => !el.matches('aside.notes, script'))
		if (content.length !== 1 || content[0].tagName !== 'H1') continue
		section.classList.add('section_divider')
		if (context) {
			const el = document.createElement('div')
			el.className = 'section_context'
			el.textContent = context
			section.prepend(el)
		}
	}
}

export default () => {

	return {
		id: 'show_title',
		// Run during init (NOT on 'ready'). This matters for print/PDF: Reveal
		// computes the print layout (measuring each slide's scrollHeight to
		// paginate) *after* all plugin init() calls but *before* the 'ready'
		// event fires. The slides are prerendered at build time, so
		// `.lecturetitle` already exists here. Injecting the title content now
		// guarantees the slide has its final height before Reveal measures it.
		init: (deck) => {
			const info = (deck.getConfig().farberg_reveal_template || {}).info
			if (!info) {
				console.log("show_title: no lecture info @ farberg_reveal_template.info (page not generated by dennis_build?)")
				return
			}
			showTitle(deck, info)
			markSectionSlides(deck)
		}
	}
}